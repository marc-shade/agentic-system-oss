logger = logging.getLogger("ecde")


class CapabilityType(Enum):
    """Types of capabilities that can be discovered."""
    PRIMITIVE = "primitive"           # Basic operation capability
    COMPOSITE = "composite"           # Combination of multiple capabilities
    META = "meta"                     # Capability about capabilities/discovery
    EMERGENT = "emergent"             # Arose unexpectedly from interactions


class DiscoveryMethod(Enum):
    """How a capability was discovered."""
    BOOTSTRAP = "bootstrap"           # Hardcoded initial capability
    HYPOTHESIS_TEST = "hypothesis"    # From hypothesis generation + testing
    COMBINATION = "combination"       # From combining existing capabilities
    ACCIDENT = "accident"             # Unexpected discovery during other tests
    META_EVOLUTION = "meta_evolution" # Discovery method improved discovery


@dataclass
class Capability:
    """
    A discovered capability of the system.

    The key insight: capabilities aren't predefined - they're discovered
    through empirical testing and can evolve through recursive improvement.
    """
    name: str
    description: str
    capability_type: CapabilityType
    discovery_method: DiscoveryMethod
    test_function: Optional[str]  # Name of test function (for serialization)
    discovered_at: str = field(default_factory=lambda: datetime.now().isoformat())
    parent_capabilities: List[str] = field(default_factory=list)
    success_rate: float = 0.0
    confidence: float = 0.0
    execution_count: int = 0
    improves_discovery: bool = False  # Key for RSI: does this help find more capabilities?
    emergence_evidence: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        """Serialize for storage/logging."""
        return {
            **asdict(self),
            "capability_type": self.capability_type.value,
            "discovery_method": self.discovery_method.value,
        }


@dataclass
class CapabilityHypothesis:
    """
    A hypothesis about a potential capability to test.

    Hypotheses are generated by the system and tested empirically.
    The hypothesis generation itself evolves based on meta-learning.
    """
    hypothesis_id: str
    description: str
    test_specification: Dict[str, Any]
    generation_strategy: str  # Which strategy generated this
    parent_hypotheses: List[str] = field(default_factory=list)
    confidence_prior: float = 0.5
    created_at: str = field(default_factory=lambda: datetime.now().isoformat())


@dataclass
class ExperimentResult:
    """Result of empirically testing a capability hypothesis."""
    hypothesis_id: str
    success: bool
    discovered_capability: Optional[Capability]
    execution_time_ms: float
    observations: List[str]
    unexpected_findings: List[str]  # Key for emergence detection
    error: Optional[str] = None


@dataclass
class DiscoveryStrategy:
    """
    A strategy for generating capability hypotheses.

    These strategies EVOLVE based on meta-learning - strategies that
    successfully discover capabilities get reinforced and refined.
    """
    name: str
    description: str
    generation_template: str
    success_rate: float = 0.0
    hypotheses_generated: int = 0
    capabilities_discovered: int = 0
    evolved_from: Optional[str] = None
    evolution_generation: int = 0

    def effectiveness(self) -> float:
        """Calculate strategy effectiveness for meta-learning."""
        if self.hypotheses_generated == 0:
            return 0.0
        return self.capabilities_discovered / self.hypotheses_generated


class EmpiricalCapabilityDiscoveryEngine:
    """
    Core ECDE engine implementing recursive capability discovery.

    THE NOVELTY:
    This engine discovers capabilities about ITSELF that couldn't be
    derived from its code, through empirical self-experimentation with
    recursive improvement of the discovery process itself.

    Unlike existing approaches:
    - Scientific method: Tests hypotheses about external world
    - A/B testing: Compares predefined variants
    - Meta-learning (MAML): Optimizes for predefined task distribution

    ECDE tests hypotheses about its OWN unknown capabilities, with no
    predefined capability space - the space itself is discovered.
    """

    def __init__(
        self,
        storage_path: Optional[Path] = None,
        max_discovery_cycles: int = 100,
        meta_learning_interval: int = 10,
    ):
        self.storage_path = storage_path or Path.home() / ".ecde"
        self.storage_path.mkdir(parents=True, exist_ok=True)

        self.max_discovery_cycles = max_discovery_cycles
        self.meta_learning_interval = meta_learning_interval

        # Core state
        self.capabilities: Dict[str, Capability] = {}
        self.strategies: Dict[str, DiscoveryStrategy] = {}
        self.hypothesis_history: List[CapabilityHypothesis] = []
        self.experiment_history: List[ExperimentResult] = []

        # Meta-learning state
        self.discovery_cycle: int = 0
        self.meta_improvements: List[Dict[str, Any]] = []
        self.emergence_log: List[Dict[str, Any]] = []

        # Capability test registry
        self._test_functions: Dict[str, Callable] = {}

        # Bootstrap
        self._bootstrap()

    def _bootstrap(self):
        """
        Initialize with minimal hardcoded capabilities and strategies.

        The bootstrap is intentionally PRIMITIVE - the power comes from
        the recursive discovery process, not from sophisticated initial
        capabilities.
        """
        logger.info("ECDE Bootstrap: Initializing minimal seed capabilities")

        # Bootstrap capability: basic task execution
        self._add_bootstrap_capability(
            name="execute_task",
            description="Can execute a simple defined task and return result",
            test_fn=self._test_execute_task
        )

        # Bootstrap capability: compare results
        self._add_bootstrap_capability(
            name="compare_results",
            description="Can compare two results for equality or similarity",
            test_fn=self._test_compare_results
        )

        # Bootstrap capability: measure time
        self._add_bootstrap_capability(
            name="measure_time",
            description="Can measure execution time of operations",
            test_fn=self._test_measure_time
        )

        # Bootstrap capability: store/retrieve
        self._add_bootstrap_capability(
            name="persist_state",
            description="Can persist and retrieve state across operations",
            test_fn=self._test_persist_state
        )

        # Bootstrap strategies (intentionally simple)
        self._add_bootstrap_strategy(
            name="combination_strategy",
            description="Generate hypotheses by combining existing capabilities",
            template="What if I combine {cap1} with {cap2}?"
        )

        self._add_bootstrap_strategy(
            name="extension_strategy",
            description="Extend a capability to a new domain",
            template="Can {capability} work in a different context?"
        )

        self._add_bootstrap_strategy(
            name="meta_strategy",
            description="Generate hypotheses about the discovery process itself",
            template="What capability about discovery am I missing?"
        )

        logger.info(f"Bootstrap complete: {len(self.capabilities)} capabilities, "
                   f"{len(self.strategies)} strategies")

    def _add_bootstrap_capability(
        self,
        name: str,
        description: str,
        test_fn: Callable
    ):
        """Add a bootstrap capability with its test function."""
        self.capabilities[name] = Capability(
            name=name,
            description=description,
            capability_type=CapabilityType.PRIMITIVE,
            discovery_method=DiscoveryMethod.BOOTSTRAP,
            test_function=f"_test_{name}",
            success_rate=1.0,  # Bootstrap capabilities are assumed working
            confidence=1.0,
            execution_count=0,
        )
        self._test_functions[name] = test_fn

    def _add_bootstrap_strategy(
        self,
        name: str,
        description: str,
        template: str
    ):
        """Add a bootstrap discovery strategy."""
        self.strategies[name] = DiscoveryStrategy(
            name=name,
            description=description,
            generation_template=template,
            evolution_generation=0,
        )

    # =========================================================================
    # BOOTSTRAP TEST FUNCTIONS
    # These are intentionally simple - the sophistication comes from discovery
    # =========================================================================

    async def _test_execute_task(self, task_spec: Dict[str, Any]) -> Dict[str, Any]:
        """Test basic task execution capability."""
        task_type = task_spec.get("type", "echo")

        if task_type == "echo":
            return {"success": True, "result": task_spec.get("input", "")}
        elif task_type == "compute":
            expr = task_spec.get("expression", "1+1")
            try:
                # Safe eval for basic math
                result = eval(expr, {"__builtins__": {}}, {})
                return {"success": True, "result": result}
            except Exception as e:
                return {"success": False, "error": str(e)}
        else:
            return {"success": False, "error": f"Unknown task type: {task_type}"}

    async def _test_compare_results(self, spec: Dict[str, Any]) -> Dict[str, Any]:
        """Test result comparison capability."""
        a, b = spec.get("a"), spec.get("b")
        comparison_type = spec.get("type", "equality")

        if comparison_type == "equality":
            return {"success": True, "result": a == b}
        elif comparison_type == "similarity":
            # Basic similarity for strings/numbers
            if isinstance(a, (int, float)) and isinstance(b, (int, float)):
                diff = abs(a - b) / max(abs(a), abs(b), 1)
                return {"success": True, "result": 1.0 - diff}
            return {"success": True, "result": 1.0 if a == b else 0.0}

        return {"success": False, "error": f"Unknown comparison: {comparison_type}"}

    async def _test_measure_time(self, spec: Dict[str, Any]) -> Dict[str, Any]:
        """Test time measurement capability."""
        operation = spec.get("operation", "sleep")
        duration = spec.get("duration", 0.01)

        start = time.perf_counter()
        if operation == "sleep":
            await asyncio.sleep(duration)
        elif operation == "compute":
            # CPU work
            total = sum(range(int(duration * 100000)))
        end = time.perf_counter()

        return {
            "success": True,
            "measured_time_ms": (end - start) * 1000,
            "expected_time_ms": duration * 1000
        }

    async def _test_persist_state(self, spec: Dict[str, Any]) -> Dict[str, Any]:
        """Test state persistence capability."""
        action = spec.get("action", "write")
        key = spec.get("key", "test_key")
        value = spec.get("value")

        state_file = self.storage_path / "test_state.json"

        if action == "write":
            try:
                state = {}
                if state_file.exists():
                    state = json.loads(state_file.read_text())
                state[key] = value
                state_file.write_text(json.dumps(state))
                return {"success": True, "action": "written", "key": key}
            except Exception as e:
                return {"success": False, "error": str(e)}

        elif action == "read":
            try:
                if not state_file.exists():
                    return {"success": True, "result": None, "exists": False}
                state = json.loads(state_file.read_text())
                return {"success": True, "result": state.get(key), "exists": key in state}
            except Exception as e:
                return {"success": False, "error": str(e)}

        return {"success": False, "error": f"Unknown action: {action}"}

    # =========================================================================
    # CORE DISCOVERY LOOP
    # This is where the novelty happens - recursive capability discovery
    # =========================================================================

    async def run_discovery_cycle(self) -> Dict[str, Any]:
        """
        Run a single discovery cycle.

        THE CORE MECHANISM:
        1. Generate hypotheses about potential capabilities
        2. Test hypotheses empirically
        3. Record discoveries and update strategies
        4. Apply meta-learning periodically

        Returns cycle results including any new discoveries.
        """
        self.discovery_cycle += 1
        cycle_start = time.perf_counter()

        logger.info(f"=== Discovery Cycle {self.discovery_cycle} ===")

        cycle_results = {
            "cycle": self.discovery_cycle,
            "hypotheses_generated": 0,
            "hypotheses_tested": 0,
            "capabilities_discovered": [],
            "unexpected_findings": [],
            "meta_improvements": [],
        }

        # Step 1: Generate hypotheses using current strategies
        hypotheses = await self._generate_hypotheses()
        cycle_results["hypotheses_generated"] = len(hypotheses)

        # Step 2: Test each hypothesis empirically
        for hypothesis in hypotheses:
            result = await self._test_hypothesis(hypothesis)
            cycle_results["hypotheses_tested"] += 1

            if result.discovered_capability:
                cycle_results["capabilities_discovered"].append(
                    result.discovered_capability.name
                )

                # KEY RSI CHECK: Does this capability improve discovery?
                if result.discovered_capability.improves_discovery:
                    logger.info(f"META-CAPABILITY DISCOVERED: "
                               f"{result.discovered_capability.name}")
                    await self._apply_meta_capability(result.discovered_capability)

            # Record unexpected findings for emergence detection
            if result.unexpected_findings:
                cycle_results["unexpected_findings"].extend(result.unexpected_findings)
                self._log_emergence_candidate(result)

        # Step 3: Periodic meta-learning (RSI mechanism)
        if self.discovery_cycle % self.meta_learning_interval == 0:
            meta_result = await self._run_meta_learning()
            cycle_results["meta_improvements"] = meta_result.get("improvements", [])

        cycle_results["cycle_time_ms"] = (time.perf_counter() - cycle_start) * 1000
        cycle_results["total_capabilities"] = len(self.capabilities)
        cycle_results["total_strategies"] = len(self.strategies)

        # Persist state
        self._save_state()

        return cycle_results

    async def _generate_hypotheses(self) -> List[CapabilityHypothesis]:
        """
        Generate capability hypotheses using current strategies.

        The hypothesis generation itself evolves through meta-learning -
        strategies that produce successful hypotheses are reinforced.
        """
        hypotheses = []

        for strategy_name, strategy in self.strategies.items():
            # Generate hypotheses based on strategy template
            new_hypotheses = await self._apply_strategy(strategy)
            hypotheses.extend(new_hypotheses)

            # Track generation count for meta-learning
            strategy.hypotheses_generated += len(new_hypotheses)

        logger.info(f"Generated {len(hypotheses)} hypotheses from "
                   f"{len(self.strategies)} strategies")

        return hypotheses

    async def _apply_strategy(
        self,
        strategy: DiscoveryStrategy
    ) -> List[CapabilityHypothesis]:
        """Apply a discovery strategy to generate hypotheses."""
        hypotheses = []

        if strategy.name == "combination_strategy":
            # Combine pairs of existing capabilities
            cap_names = list(self.capabilities.keys())
            if len(cap_names) >= 2:
                # Sample pairs to avoid explosion
                for _ in range(min(3, len(cap_names))):
                    c1, c2 = random.sample(cap_names, 2)
                    hypotheses.append(self._create_combination_hypothesis(c1, c2, strategy))

        elif strategy.name == "extension_strategy":
            # Extend each capability to new context
            for cap_name in list(self.capabilities.keys())[:3]:
                hypotheses.append(self._create_extension_hypothesis(cap_name, strategy))

        elif strategy.name == "meta_strategy":
            # Generate hypotheses about discovery itself
            hypotheses.append(self._create_meta_hypothesis(strategy))

        elif strategy.name.startswith("evolved_"):
            # Handle evolved strategies (from meta-learning)
            hypotheses.extend(await self._apply_evolved_strategy(strategy))

        return hypotheses

    def _create_combination_hypothesis(
        self,
        cap1: str,
        cap2: str,
        strategy: DiscoveryStrategy
    ) -> CapabilityHypothesis:
        """Create hypothesis about combining two capabilities."""
        return CapabilityHypothesis(
            hypothesis_id=self._generate_id("hyp"),
            description=f"Combining {cap1} and {cap2} creates new capability",
            test_specification={
                "type": "combination",
                "capabilities": [cap1, cap2],
                "test_sequence": [
                    {"use": cap1, "input": "test_data"},
                    {"use": cap2, "input": "from_previous"},
                ]
            },
            generation_strategy=strategy.name,
            parent_hypotheses=[],
        )

    def _create_extension_hypothesis(
        self,
        cap_name: str,
        strategy: DiscoveryStrategy
    ) -> CapabilityHypothesis:
        """Create hypothesis about extending a capability."""
        return CapabilityHypothesis(
            hypothesis_id=self._generate_id("hyp"),
            description=f"Extending {cap_name} to novel context",
            test_specification={
                "type": "extension",
                "base_capability": cap_name,
                "new_context": "concurrent_execution",
            },
            generation_strategy=strategy.name,
        )

    def _create_meta_hypothesis(
        self,
        strategy: DiscoveryStrategy
    ) -> CapabilityHypothesis:
        """Create hypothesis about meta-capabilities."""
        # Analyze current discovery effectiveness
        effective_strategies = [
            s.name for s in self.strategies.values()
            if s.effectiveness() > 0.3
        ]

        return CapabilityHypothesis(
            hypothesis_id=self._generate_id("meta"),
            description="Can I discover a pattern in successful discoveries?",
            test_specification={
                "type": "meta_analysis",
                "analyze_strategies": effective_strategies,
                "look_for": "common_patterns",
            },
            generation_strategy=strategy.name,
        )

    async def _apply_evolved_strategy(
        self,
        strategy: DiscoveryStrategy
    ) -> List[CapabilityHypothesis]:
        """Apply an evolved strategy (created through meta-learning)."""
        # Evolved strategies have custom generation logic stored in template
        hypotheses = []

        try:
            # Parse evolved strategy template
            template_data = json.loads(strategy.generation_template)
            focus_area = template_data.get("focus", "general")

            if focus_area == "high_yield_combinations":
                # Focus on combinations of successful capability types
                successful_caps = [
                    c for c in self.capabilities.values()
                    if c.success_rate > 0.7
                ]
                for c1 in successful_caps[:2]:
                    for c2 in successful_caps[:2]:
                        if c1.name != c2.name:
                            hypotheses.append(CapabilityHypothesis(
                                hypothesis_id=self._generate_id("evolved"),
                                description=f"High-yield combination: {c1.name} + {c2.name}",
                                test_specification={
                                    "type": "evolved_combination",
                                    "capabilities": [c1.name, c2.name],
                                    "optimization": "yield",
                                },
                                generation_strategy=strategy.name,
                            ))

        except json.JSONDecodeError:
            logger.warning(f"Could not parse evolved strategy: {strategy.name}")

        return hypotheses

    async def _test_hypothesis(
        self,
        hypothesis: CapabilityHypothesis
    ) -> ExperimentResult:
        """
        Empirically test a capability hypothesis.

        This is where the "empirical" in ECDE happens - we actually
        execute tests to see if hypothesized capabilities exist.
        """
        start_time = time.perf_counter()
        observations = []
        unexpected_findings = []
        discovered_capability = None
        error = None

        try:
            spec = hypothesis.test_specification
            test_type = spec.get("type")

            if test_type == "combination":
                result = await self._test_combination(spec)
            elif test_type == "extension":
                result = await self._test_extension(spec)
            elif test_type == "meta_analysis":
                result = await self._test_meta_analysis(spec)
            elif test_type == "evolved_combination":
                result = await self._test_evolved_combination(spec)
            else:
                result = {"success": False, "error": f"Unknown test type: {test_type}"}

            # Analyze result
            if result.get("success"):
                observations.append(f"Test succeeded: {result.get('summary', 'no summary')}")

                # Check if this reveals a new capability
                if result.get("new_capability"):
                    discovered_capability = await self._create_discovered_capability(
                        hypothesis, result
                    )
                    observations.append(f"New capability discovered: {discovered_capability.name}")
            else:
                observations.append(f"Test failed: {result.get('error', 'unknown error')}")

            # Check for unexpected findings (potential emergent behavior)
            if result.get("unexpected"):
                unexpected_findings.extend(result["unexpected"])
                observations.append(f"Unexpected findings: {len(result['unexpected'])}")

        except Exception as e:
            error = str(e)
            observations.append(f"Exception during test: {error}")
            logger.exception(f"Error testing hypothesis {hypothesis.hypothesis_id}")

        elapsed_ms = (time.perf_counter() - start_time) * 1000

        # Update strategy stats
        strategy = self.strategies.get(hypothesis.generation_strategy)
        if strategy and discovered_capability:
            strategy.capabilities_discovered += 1

        # Store in history
        result = ExperimentResult(
            hypothesis_id=hypothesis.hypothesis_id,
            success=discovered_capability is not None,
            discovered_capability=discovered_capability,
            execution_time_ms=elapsed_ms,
            observations=observations,
            unexpected_findings=unexpected_findings,
            error=error,
        )

        self.experiment_history.append(result)
        self.hypothesis_history.append(hypothesis)

        return result

    async def _test_combination(self, spec: Dict[str, Any]) -> Dict[str, Any]:
        """Test combining two capabilities."""
        cap_names = spec.get("capabilities", [])

        if len(cap_names) < 2:
            return {"success": False, "error": "Need at least 2 capabilities"}

        cap1, cap2 = cap_names[0], cap_names[1]

        if cap1 not in self.capabilities or cap2 not in self.capabilities:
            return {"success": False, "error": "Capability not found"}

        # Test if combination produces valid output
        test_fn1 = self._test_functions.get(cap1)
        test_fn2 = self._test_functions.get(cap2)

        if not test_fn1 or not test_fn2:
            return {"success": False, "error": "Test function not found"}

        # Execute combination
        result1 = await test_fn1({"type": "echo", "input": "test_data"})
        if not result1.get("success"):
            return {"success": False, "error": "First capability failed"}

        # Pass result to second capability
        result2 = await test_fn2({"type": "equality", "a": result1.get("result"), "b": "test_data"})

        # Determine if combination is novel
        combination_id = f"{cap1}__{cap2}"
        if combination_id not in self.capabilities:
            return {
                "success": True,
                "new_capability": True,
                "summary": f"Combination of {cap1} and {cap2} works",
                "combination_output": result2,
            }

        return {"success": True, "new_capability": False, "summary": "Combination already known"}

    async def _test_extension(self, spec: Dict[str, Any]) -> Dict[str, Any]:
        """Test extending a capability to a new context."""
        base_cap = spec.get("base_capability")
        new_context = spec.get("new_context")

        if base_cap not in self.capabilities:
            return {"success": False, "error": "Base capability not found"}

        test_fn = self._test_functions.get(base_cap)
        if not test_fn:
            return {"success": False, "error": "Test function not found"}

        unexpected = []

        # Test in new context (concurrent execution)
        if new_context == "concurrent_execution":
            tasks = [
                test_fn({"type": "echo", "input": f"concurrent_{i}"})
                for i in range(3)
            ]

            results = await asyncio.gather(*tasks, return_exceptions=True)

            successes = sum(1 for r in results if isinstance(r, dict) and r.get("success"))

            if successes == 3:
                # Check if this reveals something unexpected
                if base_cap == "execute_task":
                    # Unexpected: might discover capability for parallel execution
                    unexpected.append("Capability works concurrently - parallel execution possible")

                return {
                    "success": True,
                    "new_capability": True,
                    "summary": f"{base_cap} extends to concurrent context",
                    "unexpected": unexpected,
                }

        return {"success": False, "error": f"Unknown context: {new_context}"}

    async def _test_meta_analysis(self, spec: Dict[str, Any]) -> Dict[str, Any]:
        """Test meta-level hypothesis about discovery patterns."""
        strategies_to_analyze = spec.get("analyze_strategies", [])

        if not strategies_to_analyze:
            return {"success": False, "error": "No strategies to analyze"}

        # Analyze what makes strategies effective
        patterns = []
        unexpected = []

        for strategy_name in strategies_to_analyze:
            strategy = self.strategies.get(strategy_name)
            if strategy and strategy.effectiveness() > 0.3:
                patterns.append({
                    "strategy": strategy_name,
                    "effectiveness": strategy.effectiveness(),
                    "template": strategy.generation_template,
                })

        if len(patterns) >= 2:
            # Look for common elements
            # This is where EMERGENCE can happen - discovering patterns
            # about discovery that weren't explicitly programmed

            # Check if effective strategies share characteristics
            if all("combine" in p["template"].lower() or "combination" in p["strategy"]
                   for p in patterns):
                unexpected.append("Pattern: combination strategies most effective")
                return {
                    "success": True,
                    "new_capability": True,
                    "summary": "Discovered meta-pattern: combinations are key",
                    "improves_discovery": True,  # This is RSI evidence!
                    "pattern_type": "combination_preference",
                    "unexpected": unexpected,
                }

        return {
            "success": True,
            "new_capability": False,
            "summary": "No strong patterns found yet",
        }

    async def _test_evolved_combination(self, spec: Dict[str, Any]) -> Dict[str, Any]:
        """Test combination from evolved strategy."""
        # Similar to regular combination but with optimization
        result = await self._test_combination(spec)

        if result.get("success") and result.get("new_capability"):
            result["evolved_discovery"] = True
            result["summary"] += " (from evolved strategy)"

        return result

    async def _create_discovered_capability(
        self,
        hypothesis: CapabilityHypothesis,
        test_result: Dict[str, Any]
    ) -> Capability:
        """Create a new capability from successful hypothesis test."""
        spec = hypothesis.test_specification

        # Determine capability type
        if test_result.get("improves_discovery"):
            cap_type = CapabilityType.META
        elif spec.get("type") == "combination":
            cap_type = CapabilityType.COMPOSITE
        elif test_result.get("unexpected"):
            cap_type = CapabilityType.EMERGENT
        else:
            cap_type = CapabilityType.PRIMITIVE

        # Generate unique name
        base_name = spec.get("type", "discovered")
        cap_id = self._generate_id(base_name)
        cap_name = f"{base_name}_{cap_id[:8]}"

        capability = Capability(
            name=cap_name,
            description=hypothesis.description,
            capability_type=cap_type,
            discovery_method=DiscoveryMethod.HYPOTHESIS_TEST,
            test_function=None,  # Dynamically created capabilities
            parent_capabilities=spec.get("capabilities", []),
            success_rate=1.0,  # Confirmed by test
            confidence=0.8,
            improves_discovery=test_result.get("improves_discovery", False),
            emergence_evidence={
                "unexpected_findings": test_result.get("unexpected", []),
                "hypothesis_id": hypothesis.hypothesis_id,
            }
        )

        # Store capability
        self.capabilities[cap_name] = capability

        logger.info(f"CAPABILITY DISCOVERED: {cap_name} (type: {cap_type.value})")

        return capability

    # =========================================================================
    # META-LEARNING (RSI MECHANISM)
    # This is the recursive self-improvement component
    # =========================================================================

    async def _run_meta_learning(self) -> Dict[str, Any]:
        """
        Run meta-learning to improve the discovery process itself.

        THIS IS THE RSI COMPONENT:
        The system analyzes what works in discovery and modifies
        its own strategies to be more effective.
        """
        logger.info("=== Running Meta-Learning (RSI) ===")

        improvements = []

        # Analyze strategy effectiveness
        effective = [(s.name, s.effectiveness()) for s in self.strategies.values()]
        effective.sort(key=lambda x: x[1], reverse=True)

        logger.info(f"Strategy effectiveness: {effective}")

        # Evolve top strategies
        if effective and effective[0][1] > 0.3:
            best_strategy = self.strategies[effective[0][0]]

            # Create evolved version
            evolved_name = f"evolved_{best_strategy.name}_gen{best_strategy.evolution_generation + 1}"

            if evolved_name not in self.strategies:
                evolved = DiscoveryStrategy(
                    name=evolved_name,
                    description=f"Evolved from {best_strategy.name}",
                    generation_template=json.dumps({
                        "focus": "high_yield_combinations" if "combination" in best_strategy.name else "general",
                        "parent": best_strategy.name,
                    }),
                    evolved_from=best_strategy.name,
                    evolution_generation=best_strategy.evolution_generation + 1,
                )

                self.strategies[evolved_name] = evolved
                improvements.append({
                    "type": "strategy_evolution",
                    "from": best_strategy.name,
                    "to": evolved_name,
                    "generation": evolved.evolution_generation,
                })

                logger.info(f"EVOLVED STRATEGY: {evolved_name}")

        # Check for meta-capabilities that can improve discovery
        meta_caps = [c for c in self.capabilities.values() if c.improves_discovery]

        for meta_cap in meta_caps:
            improvement = await self._apply_meta_capability(meta_cap)
            if improvement:
                improvements.append(improvement)

        # Record meta-learning event
        meta_event = {
            "cycle": self.discovery_cycle,
            "improvements": improvements,
            "strategy_count": len(self.strategies),
            "timestamp": datetime.now().isoformat(),
        }
        self.meta_improvements.append(meta_event)

        return meta_event

    async def _apply_meta_capability(
        self,
        capability: Capability
    ) -> Optional[Dict[str, Any]]:
        """Apply a meta-capability to improve discovery."""
        evidence = capability.emergence_evidence

        if "combination_preference" in str(evidence):
            # Apply learned preference for combinations
            combination_strategy = self.strategies.get("combination_strategy")
            if combination_strategy:
                # Boost combination strategy (crude but demonstrates the pattern)
                old_rate = combination_strategy.success_rate
                combination_strategy.success_rate = min(1.0, old_rate + 0.1)

                return {
                    "type": "meta_capability_applied",
                    "capability": capability.name,
                    "effect": f"Boosted combination_strategy success_rate: {old_rate:.2f} -> {combination_strategy.success_rate:.2f}",
                }

        return None

    def _log_emergence_candidate(self, result: ExperimentResult):
        """Log potential emergent behavior for external validation."""
        if not result.unexpected_findings:
            return

        self.emergence_log.append({
            "cycle": self.discovery_cycle,
            "hypothesis_id": result.hypothesis_id,
            "unexpected_findings": result.unexpected_findings,
            "timestamp": datetime.now().isoformat(),
            "capability_discovered": result.discovered_capability.name if result.discovered_capability else None,
        })

